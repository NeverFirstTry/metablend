// node scripts/zh-hans-table.mjs TSCharacters.txt — writes lib/zh-hans-table.js, the traditional → simplified
// character pairs lib/zh-hans.js converts with, from OpenCC's TSCharacters.txt:
//   curl -sO https://raw.githubusercontent.com/BYVoid/OpenCC/ver.1.1.9/data/dictionary/TSCharacters.txt
// One character to one (the first simplified form where OpenCC lists several); characters that stay the same
// are left out.
import fs from 'node:fs'

const src = fs.readFileSync(process.argv[2], 'utf8')
let pairs = '', n = 0
for (const line of src.split(/\r?\n/)) {
  if (!line || line.startsWith('#')) continue
  const [t, s] = line.split('\t')
  const to = s?.split(' ')[0]
  if (!t || !to || [...t].length !== 1 || [...to].length !== 1 || t === to) continue
  pairs += t + to
  n++
}
const head = `// Traditional Chinese characters and their simplified form, in pairs (traditional, simplified), from
// OpenCC's TSCharacters.txt (https://github.com/BYVoid/OpenCC, tag ver.1.1.9, Apache License 2.0; the first
// simplified form where it lists several). Used by lib/zh-hans.js. Generated by scripts/zh-hans-table.mjs.
`
fs.writeFileSync(new URL('../lib/zh-hans-table.js', import.meta.url), `${head}const PAIRS = ${JSON.stringify(pairs)}\nexport default PAIRS\n`)
console.log(`lib/zh-hans-table.js: ${n} pairs`)
