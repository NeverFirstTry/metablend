// The home-screen widgets' look for the native build, generated from the approved spec so nothing is typed twice:
// the colours (section 2), the widget texts in 13 languages (section 10) and the icons and scenery (the SVGs).
// Writes, for Android: res/values(-night)/widget_colors.xml, res/drawable(-night)/w_*.xml and widget/WidgetText.java;
// for iOS: MetaBlendWidgets/WidgetLook.swift and one template image set per SVG in MetaBlendWidgets/Assets.xcassets.
// Run it again after a change to the spec or the assets, and commit what it writes.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../..')
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name)
  return path.resolve(ROOT, i > 0 ? process.argv[i + 1] : fallback)
}
const SPEC = fs.readFileSync(arg('--spec', 'docs/widgets-spec.md'), 'utf8')
const ASSETS = arg('--assets', 'store/design/widgets/assets')
const RES = path.join(ROOT, 'mobile/android/app/src/main/res')
const JAVA = path.join(ROOT, 'mobile/android/app/src/main/java/app/metablend/widget')
const IOS = path.join(ROOT, 'mobile/ios/App/MetaBlendWidgets')
const HEAD = 'Generated by scripts/brand/widget-native.mjs from docs/widgets-spec.md. Do not edit by hand.'

const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text.endsWith('\n') ? text : text + '\n')
}

// a markdown table after a heading: rows of trimmed cells
function table(after) {
  const at = SPEC.indexOf(after)
  if (at < 0) throw new Error(`spec: no "${after}"`)
  const lines = SPEC.slice(at).split(/\r?\n/)
  const start = lines.findIndex(l => l.startsWith('|'))
  const rows = []
  for (const l of lines.slice(start)) {
    if (!l.startsWith('|')) break
    rows.push(l.slice(1, -1).split('|').map(c => c.trim()))
  }
  return rows.filter(r => !r.every(c => /^-+$/.test(c)))
}

// ---- colours (section 2): the role rows are one hex per theme and appearance
export const THEMES = ['default', 'mono', 'winter', 'sky']
export const ROLES = ['ink', 'muted', 'window', 'rain', 'sun', 'moon', 'cloud']
const colourRows = table('## 2. Colours')
const cols = colourRows[0].slice(1).map(h => h.toLowerCase().split(' ')) // ['default', 'dark'], ...
const COLOURS = {} // COLOURS[theme][dark|light][role] = '#rrggbb'
for (const t of THEMES) COLOURS[t] = { dark: {}, light: {} }
for (const role of ROLES) {
  const row = colourRows.find(r => r[0].toLowerCase().startsWith(role))
  if (!row) throw new Error(`spec: no colour row for ${role}`)
  row.slice(1).forEach((hex, i) => {
    const m = hex.match(/`(#[0-9a-f]{6})`/i)
    if (!m) throw new Error(`spec: ${role} / ${cols[i].join(' ')} is not one colour: ${hex}`)
    const [theme, mode] = cols[i]
    COLOURS[theme][mode][role] = m[1].toLowerCase()
  })
}
// the backgrounds (the spec's first row is prose): top to bottom, [colour, position]
const BG = {
  default: { dark: [['#0f151b', 0]], light: [['#ffffff', 0]] },
  mono: { dark: [['#000000', 0]], light: [['#ffffff', 0]] },
  winter: { dark: [['#0f151b', 0]], light: [['#e3ecf7', 0], ['#f4f8fc', 1]] },
  sky: { dark: [['#1b2452', 0], ['#352f62', 0.55], ['#4f4072', 1]], light: [['#eaf3fd', 0], ['#c6dcf5', 1]] },
}
const bgRow = colourRows.find(r => r[0].startsWith('Background')).join(' ').toLowerCase()
for (const t of THEMES) for (const m of ['dark', 'light']) for (const [c] of BG[t][m]) if (!bgRow.includes(c)) throw new Error(`spec: background ${c} not in the table`)

// ---- texts (section 10)
const settingsRows = table('### Settings screen').slice(1)
const messageRows = table('### Messages').slice(1)
export const LANGS = ['en', 'de', 'fr', 'es', 'it', 'nl', 'pl', 'cs', 'sl', 'pt', 'ja', 'zh', 'ko']
const SETTINGS_KEYS = ['settings', 'city', 'home', 'show', 'hours', 'days', 'save']
const MESSAGE_KEYS = ['openOnce', 'pickCity', 'planHike', 'offline']
const TEXTS = {}
for (const lang of LANGS) {
  const s = settingsRows.find(r => r[0] === lang), m = messageRows.find(r => r[0] === lang)
  if (!s || !m) throw new Error(`spec: no texts for ${lang}`)
  TEXTS[lang] = Object.fromEntries([...SETTINGS_KEYS.map((k, i) => [k, s[i + 1]]), ...MESSAGE_KEYS.map((k, i) => [k, m[i + 1]])])
  for (const [k, v] of Object.entries(TEXTS[lang])) {
    if (!v) throw new Error(`spec: ${lang}.${k} is empty`)
    if (/[–—]/.test(v)) throw new Error(`spec: ${lang}.${k} has a dash`)
  }
}

// ---- SVG → path data
const num = n => +n
function svgPaths(svg) {
  const out = []
  for (const m of svg.matchAll(/<(path|circle|rect)\b([^>]*)\/?>/g)) {
    const a = Object.fromEntries([...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map(x => [x[1], x[2]]))
    if (m[1] === 'path') out.push(a.d)
    if (m[1] === 'circle') {
      const [cx, cy, r] = [a.cx, a.cy, a.r].map(num)
      out.push(`M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0z`)
    }
    if (m[1] === 'rect') {
      const [x, y, w, h] = [a.x, a.y, a.width, a.height].map(num), r = num(a.rx ?? 0)
      out.push(`M${x + r},${y}H${x + w - r}A${r},${r} 0 0 1 ${x + w},${y + r}V${y + h - r}A${r},${r} 0 0 1 ${x + w - r},${y + h}H${x + r}A${r},${r} 0 0 1 ${x},${y + h - r}V${y + r}A${r},${r} 0 0 1 ${x + r},${y}Z`)
    }
  }
  return out
}
const viewBox = svg => svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(num)
const size = svg => [num(svg.match(/width="([\d.]+)"/)[1]), num(svg.match(/height="([\d.]+)"/)[1])]

const svgs = fs.readdirSync(ASSETS).filter(f => f.endsWith('.svg')).sort()
if (svgs.length !== 17) throw new Error(`expected the 17 assets, found ${svgs.length}`)
const ICON_NAMES = svgs.filter(f => f.startsWith('icon-')).map(f => f.slice(0, -4))
const read = f => fs.readFileSync(path.join(ASSETS, f), 'utf8')
const androidName = n => 'w_' + n.replace(/^icon-/, 'ic_').replace(/-/g, '_')

const VEC = 'xmlns:android="http://schemas.android.com/apk/res/android"'
const AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
const xml = body => `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${HEAD} -->\n${body}`

// the icons: stroked outlines, tinted at run time
for (const n of ICON_NAMES) {
  const svg = read(`${n}.svg`)
  const paths = svgPaths(svg).map(d => `    <path android:pathData="${d}" android:strokeColor="#FF000000" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />`)
  write(path.join(RES, 'drawable', `${androidName(n)}.xml`), xml(`<!-- lucide ${n.slice(5)} (ISC) -->\n<vector ${VEC} android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths.join('\n')}\n</vector>`))
}

// the scenery: white artwork, its colour and opacity per appearance on the whole drawable (overlaps read as one shape)
const argb = (hex, alpha = 1) => '#' + Math.round(alpha * 255).toString(16).padStart(2, '0').toUpperCase() + hex.slice(1).toUpperCase()
function scenery(file, name, light, dark) {
  const svg = read(file), [x, y, vw, vh] = viewBox(svg), [w, h] = size(svg)
  for (const [dir, [hex, alpha]] of [['drawable', light], ['drawable-night', dark]]) {
    const paths = svgPaths(svg).map(d => `        <path android:pathData="${d}" android:fillColor="${argb(hex)}" />`)
    write(path.join(RES, dir, `${name}.xml`), xml(`<vector ${VEC} android:width="${w}dp" android:height="${h}dp" android:viewportWidth="${vw}" android:viewportHeight="${vh}" android:alpha="${alpha}">\n    <group android:translateX="${-x}" android:translateY="${-y}">\n${paths.join('\n')}\n    </group>\n</vector>`))
  }
}
scenery('winter-specks.svg', 'w_winter_specks', ['#ffffff', 1], ['#f6f8fc', 0.3])
scenery('winter-snow.svg', 'w_winter_snow', ['#ffffff', 1], ['#e9eef5', 0.22])
scenery('sky-cloud.svg', 'w_sky_cloud_large', ['#ffffff', 0.6], ['#ffffff', 0.09])
scenery('sky-cloud.svg', 'w_sky_cloud_small', ['#ffffff', 0.85], ['#ffffff', 0.14])

// the glows (section 3): an elliptical radial gradient in a 100 x 100 viewport, stretched over the widget; dark only
const EMPTY = xml(`<shape ${VEC} android:shape="rectangle">\n    <solid android:color="#00000000" />\n</shape>`)
function glow(name, [cx, cy], [rx, ry], hex, alpha, fade) {
  write(path.join(RES, 'drawable', `${name}.xml`), EMPTY)
  write(path.join(RES, 'drawable-night', `${name}.xml`), xml(`<vector ${VEC} ${AAPT} android:width="100dp" android:height="100dp" android:viewportWidth="100" android:viewportHeight="100">
    <group android:pivotX="${cx}" android:pivotY="${cy}" android:scaleY="${+(ry / rx).toFixed(4)}">
        <path android:pathData="M-400,-400h1000v1000h-1000z">
            <aapt:attr name="android:fillColor">
                <gradient android:type="radial" android:centerX="${cx}" android:centerY="${cy}" android:gradientRadius="${rx}">
                    <item android:offset="0" android:color="${argb(hex, alpha)}" />
                    <item android:offset="${fade}" android:color="${argb(hex, 0)}" />
                </gradient>
            </aapt:attr>
        </path>
    </group>
</vector>`))
}
glow('w_sheen_dawn', [0, 0], [90, 70], '#ffd98a', 0.09, 0.7)
glow('w_sheen_day', [50, 0], [110, 55], '#ffd98a', 0.08, 0.8)
glow('w_sheen_dusk', [100, 0], [90, 70], '#ffc470', 0.1, 0.7)
glow('w_sky_peach', [100, 115], [90, 60], '#e8957a', 0.3, 0.7)

// the backgrounds: the root's shape, so its outline clips the scenery to the corners
for (const t of THEMES) {
  for (const [dir, mode] of [['drawable', 'light'], ['drawable-night', 'dark']]) {
    const stops = BG[t][mode]
    const fill = stops.length === 1
      ? `    <solid android:color="${stops[0][0]}" />`
      : `    <gradient android:angle="270" android:startColor="${stops[0][0]}"${stops.length === 3 ? ` android:centerColor="${stops[1][0]}" android:centerY="${stops[1][1]}"` : ''} android:endColor="${stops.at(-1)[0]}" />`
    write(path.join(RES, dir, `w_bg_${t}.xml`), xml(`<shape ${VEC} android:shape="rectangle">\n${fill}\n    <corners android:radius="@dimen/w_radius" />\n</shape>`))
  }
}
write(path.join(RES, 'values', 'widget_dimens.xml'), xml(`<resources>\n    <dimen name="w_radius">24dp</dimen>\n</resources>`))
write(path.join(RES, 'values-v31', 'widget_dimens.xml'), xml(`<resources>\n    <dimen name="w_radius">@android:dimen/system_app_widget_background_radius</dimen>\n</resources>`))

for (const [dir, mode] of [['values', 'light'], ['values-night', 'dark']]) {
  const lines = THEMES.flatMap(t => ROLES.map(r => `    <color name="w_${t}_${r}">${COLOURS[t][mode][r]}</color>`))
  write(path.join(RES, dir, 'widget_colors.xml'), xml(`<resources>\n${lines.join('\n')}\n</resources>`))
}

// ---- Android: the texts and the colour resources by theme and role
const jstr = s => JSON.stringify(s)
const KEYS = [...SETTINGS_KEYS, ...MESSAGE_KEYS]
write(path.join(JAVA, 'WidgetText.java'), `// ${HEAD}
package app.metablend.widget;

import app.metablend.R;
import java.util.HashMap;
import java.util.Map;

// The widgets' texts and their settings screen in the app's 13 languages (the language arrives with the app's sync),
// and the colour resources per theme and role (light in values, dark in values-night).
public final class WidgetText {
    private static final String[] KEYS = { ${KEYS.map(jstr).join(', ')} };
    private static final Map<String, String[]> T = new HashMap<>();

    static {
${LANGS.map(l => `        T.put(${jstr(l)}, new String[] { ${KEYS.map(k => jstr(TEXTS[l][k])).join(', ')} });`).join('\n')}
    }

    public static final String[] THEMES = { ${THEMES.map(jstr).join(', ')} };
    public static final int INK = 0, MUTED = 1, WINDOW = 2, RAIN = 3, SUN = 4, MOON = 5, CLOUD = 6;
    public static final int[][] COLORS = {
${THEMES.map(t => `        { ${ROLES.map(r => `R.color.w_${t}_${r}`).join(', ')} },`).join('\n')}
    };
    public static final int[] BACKGROUNDS = { ${THEMES.map(t => `R.drawable.w_bg_${t}`).join(', ')} };

    private final String[] row;

    public WidgetText(String lang) {
        String[] r = T.get(lang);
        row = r != null ? r : T.get("en");
    }

    public String get(String key) {
        for (int i = 0; i < KEYS.length; i++) if (KEYS[i].equals(key)) return row[i];
        return key;
    }
}
`)

// ---- iOS: the texts, the palette and the backgrounds; the image sets
const sstr = s => JSON.stringify(s)
const swiftColour = hex => `Color(hex: "${hex}")`
write(path.join(IOS, 'WidgetLook.swift'), `// ${HEAD}
import SwiftUI

// The widgets' texts in the app's 13 languages: the row the app syncs, else the phone's language, else English.
enum Texts {
    enum Key: Int { case home, openOnce, pickCity, planHike, offline }
    private static let table: [String: [String]] = [
${LANGS.map(l => `        ${sstr(l)}: [${['home', ...MESSAGE_KEYS].map(k => sstr(TEXTS[l][k])).join(', ')}],`).join('\n')}
    ]
    static func t(_ lang: String?, _ key: Key) -> String {
        let phone = Locale.current.language.languageCode?.identifier ?? "en"
        let row = table[lang ?? phone] ?? table["en"]!
        return row[key.rawValue]
    }
}

struct Palette {
    let ink: Color
    let muted: Color
    let window: Color
    let rain: Color
    let sun: Color
    let moon: Color
    let cloud: Color
}

// Default for every app icon but Mono, Winter and Sky (docs/widgets-spec.md, section 1)
enum WidgetTheme: String {
    case standard = "default", mono, winter, sky

    init(_ name: String?) { self = WidgetTheme(rawValue: name ?? "") ?? .standard }

    func palette(dark: Bool) -> Palette {
        switch (self, dark) {
${THEMES.flatMap(t => [true, false].map(d => {
  const c = COLOURS[t][d ? 'dark' : 'light']
  return `        case (.${t === 'default' ? 'standard' : t}, ${d}): return Palette(${ROLES.map(r => `${r}: ${swiftColour(c[r])}`).join(', ')})`
})).join('\n')}
        }
    }

    // top to bottom
    func background(dark: Bool) -> [Gradient.Stop] {
        switch (self, dark) {
${THEMES.flatMap(t => [true, false].map(d => {
  const stops = BG[t][d ? 'dark' : 'light']
  const list = (stops.length === 1 ? [stops[0], [stops[0][0], 1]] : stops).map(([c, at]) => `.init(color: ${swiftColour(c)}, location: ${at})`)
  return `        case (.${t === 'default' ? 'standard' : t}, ${d}): return [${list.join(', ')}]`
})).join('\n')}
        }
    }
}
`)

